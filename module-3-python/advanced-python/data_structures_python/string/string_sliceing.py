str="brijesh kumar pandey"
# slice method
print(str[0]) # it will print the first character of the string
print(str[:-1]) # it will print the string except the last character
print(str[0:7]) # it will print from index 0 to 6 (7 is not included)
print(str[8:13]) # it will print from index 8 to 12 (13 is not included)
print(str[14:]) # it will print from index 14 to the end of the string
print(str[:7]) # it will print from the beginning of the string to index 6      
